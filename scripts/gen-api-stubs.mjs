#!/usr/bin/env node
/**
 * 生成供 API 文档使用的声明桩（stub）。
 *
 * 背景：
 * 库里的模块为了做到「每个实例持有独立的 Cesium 闭包」，真正的类 / 构造函数都声明在
 * `createXxxModule()` 内部，或者方法在 `_installXxx()` 里动态挂到 `this` 上，最终导出
 * 的只是一个变量。TypeDoc 因此只能看到 `const Graphics`，300 多个方法连同源码里写好
 * 的 `@example` 全部进不了文档。
 *
 * 做法（按模块的实际写法分三种策略）：
 * 1. 有 `XxxInstance` 接口 -> 以接口成员为公开 API 清单，再按名字回贴源码 JSDoc；
 * 2. 工厂内部是 `class Xxx {}` -> 直接搬类成员与 JSDoc；
 * 3. 工厂内部是构造函数 + `Xxx.prototype = { ... }` -> 搬原型上的方法。
 *
 * 产物：src/utils/cesiumPluginsExtends/api/*.ts（已 gitignore，不参与打包）
 *
 * 用法：node scripts/gen-api-stubs.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'

const ROOT = path.resolve(import.meta.dirname, '..')
const LIB_DIR = path.join(ROOT, 'src/utils/cesiumPluginsExtends/libs')
const OUT_DIR = path.join(ROOT, 'src/utils/cesiumPluginsExtends/api')

/** 不参与文档生成的实现文件 */
const SKIP_FILES = new Set(['index.ts', 'heatmap.ts', 'glsl'])

/** 参与文档生成的源码目录：libs/ 下的模块，以及 libs/plot 下的标绘箭头 */
const SOURCE_DIRS = [
  { dir: LIB_DIR, sub: '', skip: SKIP_FILES },
  {
    dir: path.join(LIB_DIR, 'plot'),
    sub: 'plot',
    skip: new Set(['index.ts', 'algorithm.ts', 'plotUtil.ts'])
  }
]

/** 生成文件头 */
const GEN_BANNER = [
  '// @generated by scripts/gen-api-stubs.mjs — 仅用于 TypeDoc，勿手工修改',
  '// @ts-nocheck',
  '/* eslint-disable */'
].join('\n')

/** 丢弃与 TypeScript 签名冲突 / 已由签名表达的 JSDoc 标签 */
const DROP_TAG_RE =
  /^\s*@(function|class|global|exports|augments|constructor|module|namespace|memberof|static|typedef|instance)\b/

/* ============================ 注释处理 ============================ */

/**
 * 把 `@param {object} options.color - 点颜色` 这类「参数对象字段」折叠成
 * `options` 参数下的一个列表，既消掉 TypeDoc 的 @param 告警，也让文档里能直接
 * 看到每个字段的含义，不用再点进 Options 接口。
 */
function foldNestedParams(lines) {
  const nested = new Map()
  const top = []
  for (const line of lines) {
    const m = line.match(/^\s*@param\s*(?:\{([^}]*)\}\s*)?([A-Za-z_$][\w$.[\]]*)\s*(?:-\s*)?(.*)$/)
    if (!m) {
      top.push(line)
      continue
    }
    const type = (m[1] || '').trim()
    const name = m[2]
    const desc = (m[3] || '').trim()
    if (!name.includes('.')) {
      top.push(`@param ${name}${desc ? ` ${desc}` : ''}`)
      continue
    }
    const [parent, ...rest] = name.split('.')
    if (!nested.has(parent)) nested.set(parent, [])
    nested.get(parent).push({ name: rest.join('.'), type, desc })
  }
  if (!nested.size) return top

  const result = []
  for (const line of top) {
    result.push(line)
    const m = line.match(/^@param\s+([A-Za-z_$][\w$]*)/)
    if (!m) continue
    const fields = nested.get(m[1])
    if (!fields) continue
    result.push('')
    for (const field of fields) {
      const typed = field.type && !/^(object|any|\*|Array|array|function)$/i.test(field.type)
      const suffix = field.desc ? `：${field.desc}` : ''
      result.push(`- \`${field.name}\`${typed ? `（\`${field.type}\`）` : ''}${suffix}`)
    }
  }
  return result
}

/**
 * 旧 JSDoc 里 `{@link module:Graphics#getLineGraphics|getLineGraphics}` 这种写法
 * TypeDoc 解析不了（会刷一堆 Failed to resolve link 警告），统一降级为代码文本。
 */
function normalizeLinks(line) {
  return line
    .replace(/\{@link\s+module:([\w$]+)#([\w$.]+)\|([^}]+)\}/g, '`$3`')
    .replace(/\{@link\s+module:([\w$]+)#([\w$.]+)[^}]*\}/g, '`$1.$2`')
}

function normalizeDoc(raw, { dropParams = false } = {}) {
  let body = raw.trim()
  body = body.replace(/^\/\*\*/, '').replace(/\*\/$/, '')
  const lines = body.split(/\r?\n/).map((line) => {
    if (/^\s*\*/.test(line)) return line.replace(/^\s*\*\s?/, '')
    // 源码里少数示例续行没写 `*`，这里去掉缩进避免出现巨大空白
    return line.replace(/^\s+/, '')
  })
  while (lines.length && !lines[0].trim()) lines.shift()
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop()

  let kept = []
  for (const line of lines) {
    if (DROP_TAG_RE.test(line)) continue
    // 旧 JSDoc 的 `@see {@link module:Graphics#x|y}` 语法 TypeDoc 无法解析，退化为纯文本
    if (/^\s*@see\b/.test(line)) {
      const link = line.match(/\{@link\s+[^|}]+\|([^}]+)\}/)
      if (link) kept.push(`@see ${link[1]}`)
      continue
    }
    if (/^\s*@returns\s*\{[^}]*\}/.test(line)) {
      kept.push(line.replace(/^(\s*)@returns\s*\{[^}]*\}\s*/, '$1@returns ').replace(/\s+$/, ''))
      continue
    }
    kept.push(normalizeLinks(line))
  }

  if (dropParams) kept = kept.filter((line) => !/^\s*@param\b/.test(line))
  else kept = foldNestedParams(kept)

  return kept.map((line) => (line.length ? ` * ${line}` : ' *')).join('\n')
}

function docFromRaw(raw, options) {
  if (!raw || !raw.startsWith('/*')) return ''
  const body = normalizeDoc(raw, options)
  return body.trim() ? `/**\n${body}\n */\n` : ''
}

/**
 * 类说明：丢掉 @param / @returns（桩里没有构造函数签名，留着只会刷告警）
 */
function classDocOf(node, text) {
  const docs = node?.jsDoc
  if (!docs || docs.length === 0) return ''
  const doc = docs[docs.length - 1]
  let start = doc.pos
  while (start < doc.end && text[start] !== '/') start += 1
  return docFromRaw(text.slice(start, doc.end), { dropParams: true })
}

/** 变量声明语句上的前导注释（`/** 模块说明 @class *\/` 常挂在这一层） */
function statementDocOf(node, text) {
  const stmt = node?.parent?.parent
  if (!stmt || !ts.isVariableStatement(stmt)) return ''
  const ranges = ts.getLeadingCommentRanges(text, stmt.getFullStart()) ?? []
  const last = ranges[ranges.length - 1]
  if (!last) return ''
  const raw = text.slice(last.pos, last.end)
  return raw.startsWith('/**') ? docFromRaw(raw, { dropParams: true }) : ''
}

/** 同名的 `var Xxx = function(...)` 构造函数的说明注释 */
function ctorDocOf(sf, className, text) {
  for (const stmt of sf.statements) {
    if (!ts.isVariableStatement(stmt)) continue
    for (const decl of stmt.declarationList.declarations) {
      if (decl.name.getText() === className) return statementDocOf(decl, text) || docOf(stmt, text)
    }
  }
  return ''
}

function docOf(node, text) {
  const docs = node?.jsDoc
  if (!docs || docs.length === 0) return ''
  const doc = docs[docs.length - 1]
  let start = doc.pos
  while (start < doc.end && text[start] !== '/') start += 1
  return docFromRaw(text.slice(start, doc.end))
}

/**
 * 模块级说明。
 *
 * 形如 `/** 图形模块 @class *\/` 的注释常常和「为每个实例创建独立闭包…」并排写在
 * 工厂函数上方，TypeScript 只会把最后一条挂到节点上，所以这里改为读前导注释，
 * 优先挑带 @class / @exports 的那条。
 */
function moduleDocOf(sf, text) {
  for (const stmt of sf.statements) {
    if (!ts.isFunctionDeclaration(stmt) || !stmt.body) continue
    if (!/^create.*Module$/.test(stmt.name?.getText() ?? '')) continue
    const ranges = ts.getLeadingCommentRanges(text, stmt.getFullStart()) ?? []
    for (const range of ranges) {
      const raw = text.slice(range.pos, range.end)
      // 这条是实现细节说明，不是模块简介，别放到 API 页上
      if (raw.includes('为每个实例创建独立闭包')) continue
      // 桩里不输出构造函数，@param 一并丢掉
      if (/@class\b|@exports\b|@module\b/.test(raw)) return docFromRaw(raw, { dropParams: true })
    }
    if (ranges.length) {
      const last = ranges[ranges.length - 1]
      const raw = text.slice(last.pos, last.end)
      if (!raw.includes('为每个实例创建独立闭包')) return docFromRaw(raw, { dropParams: true })
    }
  }
  return ''
}

/* ============================ AST 工具 ============================ */

function identName(name) {
  if (!name) return null
  if (ts.isIdentifier(name) || ts.isStringLiteral(name)) return name.text
  return null
}

function declaredNames(node) {
  if (
    ts.isMethodDeclaration(node) ||
    ts.isPropertyDeclaration(node) ||
    ts.isPropertyAssignment(node) ||
    ts.isMethodSignature(node) ||
    ts.isPropertySignature(node) ||
    ts.isGetAccessorDeclaration(node)
  ) {
    const n = identName(node.name)
    return n ? [n] : []
  }
  if (ts.isVariableDeclaration(node) || ts.isFunctionDeclaration(node) || ts.isClassDeclaration(node)) {
    const n = identName(node.name)
    return n ? [n] : []
  }
  // `this.foo = ...` / `Xxx.prototype.foo = ...`
  if (
    ts.isBinaryExpression(node) &&
    node.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
    ts.isPropertyAccessExpression(node.left)
  ) {
    return [node.left.name.text]
  }
  return []
}

/** 扫描全文件：成员名 -> JSDoc（优先带 @example 的那份） */
function buildDocIndex(sf, text) {
  const index = new Map()
  const visit = (node) => {
    if (node.jsDoc?.length) {
      const doc = docOf(node, text)
      if (doc) {
        for (const name of declaredNames(node)) {
          const prev = index.get(name)
          if (!prev || (doc.includes('@example') && !prev.includes('@example'))) index.set(name, doc)
        }
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(sf)
  return index
}

function hasModifier(node, kind) {
  return Boolean(node.modifiers?.some((m) => m.kind === kind))
}

function stripModifiers(sig) {
  return sig
    .replace(/^(export\s+)?(default\s+)?(declare\s+)?/, '')
    .replace(/^(public|private|protected|readonly|static|async|abstract)\s+/g, '')
    .trim()
}

function unwrapExpression(node) {
  let cur = node
  while (cur && (ts.isAsExpression(cur) || ts.isSatisfiesExpression(cur) || ts.isParenthesizedExpression(cur))) {
    cur = cur.expression
  }
  return cur
}

/** 工厂内部声明了真正的 class 的模块（Graphics / Base / Material ...） */
function classesInFactory(sf) {
  const result = []
  const visit = (node) => {
    if (ts.isClassDeclaration(node) && node.name) result.push(node)
    ts.forEachChild(node, visit)
  }
  for (const stmt of sf.statements) {
    if (!ts.isFunctionDeclaration(stmt) || !stmt.body) continue
    if (!/^create.*Module$/.test(stmt.name?.getText() ?? '')) continue
    ts.forEachChild(stmt.body, visit)
  }
  return result
}

/** 构造函数 + 原型对象的模块（Draw / Plugin / Primitive / 标绘箭头 ...） */
function prototypeTarget(sf) {
  const ctors = new Map()
  const collect = (node) => {
    if (ts.isVariableDeclaration(node) && node.name && node.initializer) {
      const init = unwrapExpression(node.initializer)
      if (init && ts.isFunctionExpression(init) && init.parameters[0]?.name?.getText() === 'this') {
        ctors.set(node.name.getText(), node)
      }
    }
    ts.forEachChild(node, collect)
  }
  collect(sf)
  if (!ctors.size) return null

  const found = []
  const scan = (node) => {
    if (
      ts.isBinaryExpression(node) &&
      node.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
      ts.isPropertyAccessExpression(node.left) &&
      node.left.name.getText() === 'prototype' &&
      ctors.has(node.left.expression.getText())
    ) {
      const obj = unwrapExpression(node.right)
      if (obj && ts.isObjectLiteralExpression(obj)) {
        const name = node.left.expression.getText()
        found.push({ name, members: obj.properties, node: ctors.get(name) })
      }
    }
    ts.forEachChild(node, scan)
  }
  scan(sf)
  found.sort((a, b) => b.members.length - a.members.length)
  return found[0] ?? null
}

/** 找到模块的实例接口（严格匹配 `XxxInstance`，并递归合并同文件里的父接口成员） */
function instanceInterface(sf, baseName) {
  const interfaces = new Map()
  for (const stmt of sf.statements) {
    if (ts.isInterfaceDeclaration(stmt)) interfaces.set(stmt.name.getText(), stmt)
  }
  const target = interfaces.get(`${baseName}Instance`)
  if (!target) return null

  const seen = new Set()
  const members = []
  const collect = (decl) => {
    if (!decl || seen.has(decl)) return
    seen.add(decl)
    for (const heritage of decl.heritageClauses ?? []) {
      for (const type of heritage.types) collect(interfaces.get(type.expression.getText()))
    }
    members.push(...decl.members)
  }
  collect(target)
  return { name: target.name.getText(), members }
}

/* ============================ 成员序列化 ============================ */

/** `any | any | any` 之类的无意义联合压平 */
function tidyType(text) {
  return text.replace(/\bany(\s*\|\s*any)+\b/g, 'any').replace(/\bunknown(\s*\|\s*unknown)+\b/g, 'unknown')
}

function signatureOf(member, text, style) {
  // 接口成员
  if (style === 'interface') {
    if (ts.isMethodSignature(member)) {
      const name = identName(member.name)
      if (!name) return null
      const params = (member.parameters || []).map((p) => text.slice(p.getStart(), p.end))
      return `${name}(${params.join(', ')})${member.type ? `: ${tidyType(member.type.getText())}` : ': any'}`
    }
    if (ts.isPropertySignature(member)) {
      const name = identName(member.name)
      if (!name || !member.type) return null
      return `${name}: ${tidyType(member.type.getText())}`
    }
    return null
  }

  // class 里的方法 / 字段
  if (ts.isMethodDeclaration(member)) {
    const name = identName(member.name)
    if (!name) return null
    const head = text.slice(member.getStart(), member.body ? member.body.getStart() : member.end)
    let sig = stripModifiers(head).replace(/\s+$/, '')
    if (!member.type) sig += ': any'
    return tidyType(sig)
  }
  if (ts.isPropertyDeclaration(member)) {
    const name = identName(member.name)
    if (!name) return null
    return `${name}: ${tidyType(member.type ? member.type.getText() : 'any')}`
  }

  // 原型对象上的 `xxx: function (this: XxxInstance, ...) {}`
  if (ts.isPropertyAssignment(member)) {
    const name = identName(member.name)
    if (!name) return null
    const fn = member.initializer
    if (!ts.isFunctionExpression(fn) && !ts.isArrowFunction(fn)) return null
    const params = (fn.parameters || [])
      .filter((p) => p.name?.getText() !== 'this')
      .map((p) => text.slice(p.getStart(), p.end))
    const ret = fn.type ? `: ${tidyType(fn.type.getText())}` : ': any'
    return `${name}(${params.join(', ')})${ret}`
  }
  return null
}

function isPrivateMember(member) {
  const name = identName(member.name)
  if (!name || name.startsWith('_') || name === 'constructor') return true
  if (member.modifiers?.some((m) => m.kind === ts.SyntaxKind.PrivateKeyword)) return true
  return false
}

/** 是否标了 @deprecated：这类成员只做向后兼容，不占正文版面 */
function isDeprecated(node) {
  return Boolean(node.jsDoc?.some((d) => d.tags?.some((t) => t.tagName.text === 'deprecated')))
}

/** 取方法/函数的参数列表（原型写法要多剥一层） */
function paramsOf(node, style) {
  if (style === 'proto') return node.initializer?.parameters ?? []
  return node.parameters ?? []
}

/** 本地接口的字段清单（含每个字段的说明与类型），用于给 `options` 参数补字段表 */
function interfaceFields(sf, typeName, text) {
  const decl = sf.statements.find((s) => ts.isInterfaceDeclaration(s) && s.name.getText() === typeName)
  if (!decl) return []
  const fields = []
  for (const member of decl.members) {
    const name = identName(member.name)
    if (!name || name.startsWith('_')) continue
    const doc = docOf(member, text)
    const desc = (doc.match(/^\s*\*\s*(\S.*)$/m) || [])[1] ?? ''
    const cleanDesc = desc.replace(/\s*\*\/\s*$/, '').trim()
    // 没有说明的字段列出来只是噪音（DrawOptions 这类共用大接口尤其明显）
    if (!cleanDesc) continue
    const type = member.type ? tidyType(member.type.getText()) : ''
    fields.push({
      name,
      type: /^(any|unknown)$/.test(type) ? '' : type,
      desc: cleanDesc
    })
  }
  return fields.slice(0, 15)
}

/** 把字段表插到 `@param options` 之后（没有则插在描述末尾、标签之前） */
function mergeFieldList(doc, fields, paramName) {
  if (!fields.length) return doc
  // 源码里已经有字段说明（生成器折叠过 @param），不重复
  if (/\n \* - `/.test(doc)) return doc
  const bullets = fields.map((f) => {
    const type = f.type ? `（\`${f.type}\`）` : ''
    return `- \`${f.name}\`${type}${f.desc ? `：${f.desc}` : ''}`
  })

  const lines = doc
    ? doc.replace(/^\/\*\*\n/, '').replace(/\n \*\/\n$/, '').split('\n')
    : []
  const body = lines.map((line) => line.replace(/^ \* ?/, ''))

  const paramIndex = body.findIndex((line) => new RegExp(`^@param\\s+${paramName}\\b`).test(line))
  const firstTag = body.findIndex((line) => /^@\w+/.test(line))
  const insertAt = paramIndex >= 0 ? paramIndex + 1 : firstTag >= 0 ? firstTag : body.length

  const block = paramIndex >= 0 ? ['', ...bullets] : [...bullets, '']
  body.splice(insertAt, 0, ...block)

  return `/**\n${body.map((line) => (line ? ` * ${line}` : ' *')).join('\n')}\n */\n`
}

/* ============================ 主流程 ============================ */

/** 从 api/ 回到源码目录的相对前缀 */
function libPath(sub) {
  return sub ? `../libs/${sub}/` : '../libs/'
}

/**
 * 桩文件在 api/，源码 import 的写法则相对 libs/ 或 libs/plot/，这里统一改写：
 * `./BasePlot` -> `../libs/plot/BasePlot`，`../Base` -> `../libs/Base`
 */
function rewriteImportPaths(text, sub) {
  return text.replace(/from\s+(["'])(\.\.?\/[^"']+)\1/g, (_, quote, spec) => {
    const target = spec.startsWith('./') ? `${libPath(sub)}${spec.slice(2)}` : `../libs/${spec.slice(3)}`
    return `from ${quote}${target}${quote}`
  })
}

function buildStub(file, sub = '') {
  const text = fs.readFileSync(file, 'utf8')
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true)
  const baseName = path.basename(file, '.ts')

  const iface = instanceInterface(sf, baseName)
  const classes = classesInFactory(sf)
  const proto = classes.length ? null : prototypeTarget(sf)

  let className = baseName
  let classDoc = ''
  let surface = []
  let style = ''

  if (iface) {
    style = 'interface'
    className = iface.name.replace(/Instance$/, '')
    classDoc = ctorDocOf(sf, className, text)
    const docIndex = buildDocIndex(sf, text)
    surface = iface.members.map((m) => ({ node: m, doc: docIndex.get(identName(m.name) ?? '') || '' }))
  } else if (classes.length) {
    style = 'class'
    const cls = classes.sort((a, b) => b.members.length - a.members.length)[0]
    className = cls.name.getText()
    classDoc = classDocOf(cls, text)
    surface = cls.members.map((m) => ({ node: m, doc: docOf(m, text) }))
  } else if (proto) {
    style = 'proto'
    className = proto.name
    // `var Xxx = function(...)` 的 JSDoc 挂在 VariableStatement 上，节点本身读不到
    classDoc = classDocOf(proto.node, text) || statementDocOf(proto.node, text)
    surface = proto.members.map((m) => ({ node: m, doc: docOf(m, text) }))
  } else {
    return null
  }

  // 模块级说明：模块注释常与工厂注释并排书写，统一走 moduleDocOf
  if (!classDoc) classDoc = moduleDocOf(sf, text)

  // 桩文件是生成的，链接不到真实实现；这里补一条源码位置，方便维护者跳转
  const sourcePath = path.relative(ROOT, file).split(path.sep).join('/')
  const seeLine = ` * @see [实现源码](https://github.com/dengxiaoning/cesium_dev_kit/blob/main/${sourcePath})`
  classDoc = classDoc
    ? classDoc.replace(/\n \*\/\n$/, `\n${seeLine}\n */\n`)
    : `/**\n${seeLine}\n */\n`

  const emitted = []
  const used = new Set()
  const skipped = []
  for (const { node, doc } of surface) {
    if (isPrivateMember(node)) continue
    const name = identName(node.name)
    if (!name || used.has(name)) continue
    // 旧拼写的兼容别名（craeteXxx）不占文档版面，类说明里统一提示一次
    if (isDeprecated(node)) {
      skipped.push(name)
      continue
    }
    const sig = signatureOf(node, text, style)
    if (!sig) continue
    used.add(name)

    // 最后一个参数若指向本地定义的 Options 接口，自动补一张字段表，
    // 让方法页上直接能读到每个字段的含义，不必再点进接口页。
    let merged = doc
    const params = paramsOf(node, style)
    const lastParam = params[params.length - 1]
    const typeName = lastParam?.type?.getText()
    if (typeName && /^[A-Za-z_$][\w$]*$/.test(typeName)) {
      const fields = interfaceFields(sf, typeName, text)
      if (fields.length) merged = mergeFieldList(doc, fields, identName(lastParam.name) ?? 'options')
    }
    emitted.push(`${merged}  ${sig}`)
  }
  if (!emitted.length) return null

  if (skipped.length) {
    const note = ` * > 已弃用的兼容别名（不再列出，请改用对应的 \`create*\` 方法）：${skipped
      .map((n) => `\`${n}\``)
      .join('、')}`
    classDoc = classDoc.replace(/\n \*\/\n$/, `\n *\n${note}\n */\n`)

    // 指向已隐藏别名的 `{@link craeteXxx}` 会变成死链，改写成代码文本
    const deadLink = new RegExp(`\\{@link\\s+(${skipped.join('|')})(?:\\|[^}]*)?\\}`, 'g')
    for (let i = 0; i < emitted.length; i += 1) {
      emitted[i] = emitted[i].replace(deadLink, '`$1`')
    }
  }

  // 归类：TypeDoc 按 @category 分组，文档目录才不会是一长串字母序
  const category = CATEGORIES[className]
  if (category) {
    classDoc = classDoc.replace(/\n \*\/\n$/, `\n * @category ${category}\n */\n`)
  }

  // 复刻源码 import（路径从 libs/ 上浮一层到 api/），再补一条本地导出类型的 import
  const importDecls = sf.statements.filter((s) => ts.isImportDeclaration(s))
  const imports = importDecls
    .map((s) => rewriteImportPaths(text.slice(s.getStart(), s.end), sub))
    .join('\n')

  const importedNames = new Set()
  for (const decl of importDecls) {
    const bindings = decl.importClause?.namedBindings
    if (bindings && ts.isNamedImports(bindings)) {
      bindings.elements.forEach((el) => importedNames.add(el.name.getText()))
    } else if (bindings && ts.isNamespaceImport(bindings)) {
      importedNames.add(bindings.name.getText())
    } else if (decl.importClause?.name) {
      importedNames.add(decl.importClause.name.getText())
    }
  }
  const localTypes = []
  const localTypeNames = new Set(importedNames)
  for (const stmt of sf.statements) {
    const exported = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
    if (!exported) continue
    const isTypeDecl = ts.isInterfaceDeclaration(stmt) || ts.isTypeAliasDeclaration(stmt) || ts.isEnumDeclaration(stmt)
    if (!isTypeDecl || !stmt.name) continue
    const name = stmt.name.getText()
    if (localTypeNames.has(name)) continue
    localTypeNames.add(name)
    localTypes.push(name)
  }
  const localTypeImport = localTypes.length
    ? `import type { ${localTypes.join(', ')} } from '${libPath(sub)}${baseName}'`
    : ''

  const importList = [
    imports,
    localTypeImport
  ].filter(Boolean)

  const header = [GEN_BANNER, ...importList].join('\n')

  const classBody = `${classDoc}export declare class ${className} {\n\n  /** @internal 构造函数由 createScopedConstructor 提供，实例请用 createKit 或 new 传入 viewer */\n  constructor()\n\n${emitted.join('\n\n')}\n}\n`

  return {
    name: baseName,
    className,
    content: `${header}\n\n${classBody}`,
    importList,
    classBody,
    count: emitted.length
  }
}

/**
 * 所有类合并进同一个入口文件。
 *
 * 单独一个文件一个类时，TypeDoc 会把每个文件当成一个模块，侧边栏变成
 * 「Graphics > Graphics」「Draw > Draw」两层，外加一堆实现文件的变量页，
 * 非常难逛。合并成单入口后，文档树就是一层类列表：一个类一页。
 */
function buildBundle(stubs) {
  const modules = new Map()
  const taken = new Map()

  for (const stub of stubs) {
    for (const line of stub.importList) {
      const parsed = parseImport(line)
      if (!parsed) continue
      // glsl 着色器类型在文档里没有可点开的内容，直接丢掉引用（签名里仍保留名字）
      if (parsed.module.includes('/glsl/')) continue
      for (const name of parsed.names) {
        const owner = taken.get(name)
        if (owner && owner !== parsed.module) continue
        taken.set(name, parsed.module)
        if (!modules.has(parsed.module)) modules.set(parsed.module, new Set())
        modules.get(parsed.module).add(name)
      }
    }
  }

  const imports = [...modules.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([module, names]) => `import type { ${[...names].sort().join(', ')} } from '${module}'`)

  const bodies = stubs
    .slice()
    .sort((a, b) => orderOf(a.className) - orderOf(b.className) || a.className.localeCompare(b.className))
    .map((s) => s.classBody.trim())

  return `${[GEN_BANNER, ...imports].join('\n')}\n\n${bodies.join('\n\n')}\n`
}

/** `import { a, b as c } from 'x'` / `import type {..}` / `import D from 'x'` */
function parseImport(line) {
  const m = line.match(/^import\s+(?:type\s+)?(?:\{([^}]*)\}|([\w$]+))\s+from\s+'([^']+)'/)
  if (!m) return null
  const names = m[1]
    ? m[1]
        .split(',')
        .map((s) => s.trim().split(/\s+as\s+/).pop())
        .filter(Boolean)
    : [m[2]]
  return { names, module: m[3] }
}

