/** 入口文件里类的排列顺序（侧边栏顺序跟着这个走） */
const CLASS_ORDER = [
  'Graphics',
  'Draw',
  'AttackArrow',
  'PincerArrow',
  'StraightArrow',
  'BasePlot',
  'Primitive',
  'Analysis',
  'Material',
  'Math2d',
  'Math3d',
  'PassEffect',
  'ThreeJs',
  'Plugin',
  'Control',
  'DomUtil',
  'TooltipUtil',
  'CustomCesiumPlugin',
  'Base'
]

function orderOf(name) {
  const i = CLASS_ORDER.indexOf(name)
  return i < 0 ? CLASS_ORDER.length : i
}

function main() {
  if (fs.existsSync(OUT_DIR)) fs.rmSync(OUT_DIR, { recursive: true, force: true })
  fs.mkdirSync(OUT_DIR, { recursive: true })

  const summary = []
  const stubs = []
  let total = 0

  for (const source of SOURCE_DIRS) {
    const files = fs
      .readdirSync(source.dir)
      .filter((f) => f.endsWith('.ts') && !source.skip.has(f) && !f.endsWith('.d.ts'))
      .sort()

    for (const file of files) {
      const stub = buildStub(path.join(source.dir, file), source.sub)
      if (!stub) continue
      stubs.push(stub)
      fs.writeFileSync(path.join(OUT_DIR, `${stub.name}.ts`), stub.content, 'utf8')
      summary.push(`${stub.name}(${stub.count})`)
      total += stub.count
    }
  }

  // 单入口：TypeDoc 只认这一个文件，于是整个文档就是「一层类、一类一页」
  fs.writeFileSync(path.join(OUT_DIR, 'index.ts'), buildBundle(stubs), 'utf8')

  console.log(`[gen-api-stubs] ${summary.length} 个类 / ${total} 个成员 -> ${path.relative(ROOT, OUT_DIR)}`)
  console.log('  ' + summary.join('  '))
}

main()
